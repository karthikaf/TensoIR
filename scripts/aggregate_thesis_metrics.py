def fmt(mean, std, decimals=2):
    """Return LaTeX string  'mean ± std'  with given decimal places."""
    fmt_str = f"{{:.{decimals}f}}"
    return f"{fmt_str.format(mean)} \\pm {fmt_str.format(std)}"

def fmt4(mean, std):
    return fmt(mean, std, decimals=4)


def find_npz(run_dir):
    """Find metrics_per_view.npz inside a run directory.
    Looks in imgs_test_all/ directly, then in any test_reeval_final*/imgs_test_all/.
    Returns path or None.
    """
    # Direct path (from training loop eval)
    direct = os.path.join(run_dir, "imgs_test_all", "metrics_per_view.npz")
    if os.path.exists(direct):
        return direct

    # Path from render_only re-eval
    pattern = os.path.join(run_dir, "test_reeval_final*", "imgs_test_all", "metrics_per_view.npz")
    matches = sorted(glob.glob(pattern))
    if matches:
        return matches[-1]  # take most recent

    return None


def load_npz(run_dir, label=""):
    path = find_npz(run_dir)
    if path is None:
        print(f"  [WARN] metrics_per_view.npz not found in {run_dir}", file=sys.stderr)
        return None
    return np.load(path)


def ms(arr):
    """Return (mean, std) as floats."""
    a = np.asarray(arr, dtype=float)
    return float(np.mean(a)), float(np.std(a, ddof=0))


# ─────────────────────────────────────────────────────────────────────────────
# Relighting helpers  (parse existing per-view relight_psnr.txt files)
# ─────────────────────────────────────────────────────────────────────────────

ENV_MAPS = ["courtyard", "snow", "sunset", "bridge", "fireplace"]

def parse_relight_per_view(scene_dir):
    """Parse all test_*/relighting_without_bg/relight_psnr.txt files.
    Returns dict: {env_name: {'psnr': [], 'ssim': [], 'lpips_vgg': []}}
    Falls back to relight_metrics_per_view.npz if available.
    """
    # Prefer .npz if already generated by the patched script
    npz_path = os.path.join(scene_dir, "relight_metrics_per_view.npz")
    if os.path.exists(npz_path):
        d = np.load(npz_path)
        result = {}
        for env in ENV_MAPS:
            psnr_key = f"psnr_{env}"
            if psnr_key in d:
                result[env] = {
                    "psnr":      d[psnr_key],
                    "ssim":      d.get(f"ssim_{env}", np.array([])),
                    "lpips_vgg": d.get(f"lpips_vgg_{env}", np.array([])),
                }
        if result:
            return result

    # Parse per-view txt files
    result = {env: {"psnr": [], "ssim": [], "lpips_vgg": []} for env in ENV_MAPS}
    view_dirs = sorted(glob.glob(os.path.join(scene_dir, "test_[0-9][0-9][0-9]")))
    for vdir in view_dirs:
        txt = os.path.join(vdir, "relighting_without_bg", "relight_psnr.txt")
        if not os.path.exists(txt):
            continue
        with open(txt) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                # Format: "courtyard: PNSR 24.19; SSIM 0.94; L_Alex 0.06; L_VGG 0.07"
                for env in ENV_MAPS:
                    if line.lower().startswith(env):
                        nums = re.findall(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", line)
                        if len(nums) >= 4:
                            result[env]["psnr"].append(float(nums[0]))
                            result[env]["ssim"].append(float(nums[1]))
                            result[env]["lpips_vgg"].append(float(nums[3]))
                        break
    return result


