RELIGHT_RUNS = {
    "repro": {
        "ficus":  os.path.join(RLIT, "vanilla_ficus"),
        "hotdog": os.path.join(RLIT, "vanilla_hotdog"),
        "lego":   os.path.join(RLIT, "vanilla_lego"),
    },
    "unified": {
        "ficus":  os.path.join(RLIT, "v6_ficus"),
        "hotdog": os.path.join(RLIT, "v6_hotdog"),
        "lego":   os.path.join(RLIT, "v6_lego"),
    },
}


def relight_stats(scene_dir):
    """Returns {env: {metric: (mean, std)}} for all env maps."""
    data = parse_relight_per_view(scene_dir)
    stats = {}
    for env, arrays in data.items():
        stats[env] = {}
        for metric, vals in arrays.items():
            if len(vals) > 0:
                stats[env][metric] = ms(np.asarray(vals, dtype=float))
            else:
                stats[env][metric] = (float("nan"), float("nan"))
    return stats


def table_46():
    """Summary table: mean over 5 env maps ± std across env maps."""
    print("\n% ── Table 4.6: Relighting summary (mean over 5 env maps) ───")
    print("% Metric & Ficus Base & Ficus Ours & Hotdog Base & Hotdog Ours & Lego Base & Lego Ours")
    for metric in ["psnr", "ssim", "lpips_vgg"]:
        cells = []
        for scene in ["ficus", "hotdog", "lego"]:
            for key in ["repro", "unified"]:
                stats = relight_stats(RELIGHT_RUNS[key][scene])
                per_env_means = [stats[e][metric][0] for e in ENV_MAPS if e in stats and metric in stats[e]]
                if per_env_means:
                    m = np.mean(per_env_means)
                    s = np.std(per_env_means, ddof=0)
                    cells.append(f"${fmt(m, s)}$")
                else:
                    cells.append("---")
        print(f"{metric.upper()} & {' & '.join(cells)} \\\\")


def table_47_49():
    """Per-environment tables for each scene.
    Column order: Env | PSNR_base±std | PSNR_ours±std | SSIM_base±std | SSIM_ours±std | LPIPS_base±std | LPIPS_ours±std
    std is across the 200 test views for that env map.
    """
    for scene_name, scene_key in [("Ficus", "ficus"), ("Hotdog", "hotdog"), ("Lego", "lego")]:
        print(f"\n% ── Table per-env: {scene_name} relighting ──────────────────")
        print("% Env & PSNR Base & PSNR Ours & SSIM Base & SSIM Ours & LPIPS Base & LPIPS Ours")
        repro_stats   = relight_stats(RELIGHT_RUNS["repro"][scene_key])
        unified_stats = relight_stats(RELIGHT_RUNS["unified"][scene_key])

        # accumulators for per-env means (used in Average row)
        acc = {m: {"base": [], "ours": []} for m in ["psnr", "ssim", "lpips_vgg"]}

        for env in ENV_MAPS:
            row_cells = [env.capitalize()]
            # For each metric, emit Base then Ours (interleaved)
            for metric in ["psnr", "ssim", "lpips_vgg"]:
                for key, stats in [("base", repro_stats), ("ours", unified_stats)]:
                    if env in stats and metric in stats[env]:
                        m, s = stats[env][metric]
                        acc[metric][key].append(m)
                        d = 2 if metric == "psnr" else 4
                        row_cells.append(f"${fmt(m, s, decimals=d)}$")
                    else:
                        row_cells.append("---")
            print(" & ".join(row_cells) + " \\\\")

        # Average row: mean of the 5 per-env means ± std across env maps
        print("\\midrule")
        avg_cells = ["\\textbf{Average}"]
        for metric in ["psnr", "ssim", "lpips_vgg"]:
            for key in ["base", "ours"]:
                vals = acc[metric][key]
                if vals:
                    m = np.mean(vals); s = np.std(vals, ddof=0)
                    d = 2 if metric == "psnr" else 4
                    avg_cells.append(f"$\\mathbf{{{fmt(m, s, decimals=d)}}}$"
                                     if key == "base" else f"${fmt(m, s, decimals=d)}$")
                else:
                    avg_cells.append("---")
        print(" & ".join(avg_cells) + " \\\\")


